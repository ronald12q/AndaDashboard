  await heading(/Tu solicitud · SOL-/)
  const address = page.url()
  const requestNumber = (await page.getByRole('heading', { name: /Tu solicitud · SOL-/ }).textContent()).split(' · ')[1]
  if (disconnect) {
    for (const [name, category] of [['identificacion.pdf', 'IDENTIFICACION'], ['escritura.pdf', 'ESCRITURA'], ['carta.pdf', 'CARTA']]) {
      await attach(name, category)
    }
    await snapshot('07-desconexion')
  }
  await button('Enviar solicitud').click()
  await status('En revisión')
  assert.equal(await button('Simular pago').count(), 0)
  await switchRole(true)
