const status = text => page.locator('.page-heading .badge').filter({ hasText: text }).waitFor()
const targetSnapshots = process.env.ANDA_SNAPSHOT_DIR
async function snapshot(name) {
  if (!targetSnapshots) return
  await mkdir(targetSnapshots, { recursive: true })
  await page.screenshot({ path: join(targetSnapshots, `${name}.png`), fullPage: name.includes('movil'), animations: 'disabled' })
}

async function logout() {
  await button('Cerrar sesión').click()
  await heading('Bienvenido de nuevo')
}
async function login(admin) {
  if (admin) await button('Personal administrativo').click()
  await page.getByLabel(admin ? 'Correo institucional' : 'DUI', { exact: true }).fill(admin ? adminEmail : dui)
  await page.getByLabel('Contraseña', { exact: true }).fill(admin ? adminPassword : password)
  await button('Ingresar').click()
  await heading(admin ? 'Solicitudes recibidas' : /^Hola,/)
}
async function switchRole(admin) {
  page = admin ? adminPage : citizenPage
  if (page.url() === 'about:blank') {
    await page.goto(`${base}/#/login`)
    await login(admin)
  } else {
    await page.goto(`${base}/#/solicitudes`)
    await page.reload()
    await heading(admin ? 'Solicitudes recibidas' : 'Mis solicitudes')
  }
}
async function attach(name, category) {
  const selector = page.getByLabel('Categoría del archivo')
  if (await selector.count()) await selector.selectOption(category)
  await page.getByLabel('Archivo de prueba').setInputFiles({
    name, mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4\n% Ficticio para pruebas\n%%EOF\n'),
  })
  await button('Adjuntar archivo').click()
  await page.getByRole('button', { name: `Descargar ${name}`, exact: true }).waitFor()
}
async function checkReceipt(requestNumber, amount) {
  const receiptDownload = page.waitForEvent('download')
  await button('Descargar comprobante simulado').click()
  const receipt = await receiptDownload
  assert.equal(receipt.suggestedFilename(), `Comprobante-SIMULADO-${requestNumber}.pdf`)
  const pdf = (await readFile(await receipt.path())).toString('ascii')
  assert.ok(pdf.startsWith('%PDF-'))
  assert.ok(pdf.includes('COMPROBANTE SIMULADO - SIN VALIDEZ FISCAL'))
  assert.ok(pdf.includes(`Solicitud: ${requestNumber}`))
  assert.ok(pdf.includes(`Importe de referencia: USD ${amount}`))
}
